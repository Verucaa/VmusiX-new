@Entity(tableName = "lyrics_cache")
data class LyricsCacheEntity(
    @PrimaryKey val trackId: String,
    val provider: String,
    val isSynced: Boolean,
    val serializedLines: String,
    val plainLyrics: String,
    val cachedAt: Long = System.currentTimeMillis()
) {
    fun toDomain(): LyricsData {
        val lines = if (serializedLines.isNotBlank()) {
            serializedLines.split("\n--LINE--\n").mapNotNull { lineStr ->
                val parts = lineStr.split("|||")
                if (parts.size >= 2) {
                    val time = parts[0].toLongOrNull() ?: 0L
                    val text = parts[1]
                    val trans = if (parts.size > 2 && parts[2].isNotBlank()) parts[2] else null
                    LyricsLine(timeMs = time, text = text, translation = trans)
                } else null
            }
        } else emptyList()

        return LyricsData(
            trackId = trackId,
            lines = lines,
            isSynced = isSynced,
            provider = runCatching { LyricsProvider.valueOf(provider) }.getOrDefault(LyricsProvider.OFFLINE_CACHE),
            plainLyrics = plainLyrics
        )
    }

    companion object {
        fun fromDomain(lyrics: LyricsData): LyricsCacheEntity {
            val serialized = lyrics.lines.joinToString("\n--LINE--\n") { line ->
                "${line.timeMs}|||${line.text}|||${line.translation ?: ""}"
            }
            return LyricsCacheEntity(
                trackId = lyrics.trackId,
                provider = lyrics.provider.name,
                isSynced = lyrics.isSynced,
                serializedLines = serialized,
                plainLyrics = lyrics.plainLyrics
            )
        }
    }
}

