@Entity(
    tableName = "tracks",
    indices = [
        Index(value = ["offlineAvailable"]),
        Index(value = ["isLiked"]),
        Index(value = ["isDownloaded"]),
        Index(value = ["localFilePath"])
    ]
)
data class TrackEntity(
    @PrimaryKey val id: String,
    val title: String,
    val artist: String,
    val artistId: String = "",
    val album: String = "",
    val albumId: String = "",
    val durationSeconds: Long = 0,
    val artworkUrl: String = "",
    val streamUrl: String = "",
    val isLiked: Boolean = false,
    val isDownloaded: Boolean = false,
    val isCached: Boolean = false,
    val localFilePath: String? = null,
    val storageState: String = "ONLINE_ONLY",
    val fileSizeBytes: Long = 0,
    val mimeType: String = "audio/mp4",
    val offlineAvailable: Boolean = false,
    val playCount: Long = 0,
    val lastPlayedAt: Long = 0,
    val cachedAt: Long = 0,
    val dateAdded: Long = System.currentTimeMillis()
) {
    fun toDomain(): Track = Track(
        id = id,
        title = title,
        artist = artist,
        artistId = artistId,
        album = album,
        albumId = albumId,
        durationSeconds = durationSeconds,
        artworkUrl = artworkUrl,
        streamUrl = streamUrl,
        isLiked = isLiked,
        isDownloaded = isDownloaded,
        isCached = isCached,
        localFilePath = localFilePath,
        storageState = runCatching { LocalStorageState.valueOf(storageState) }
            .getOrDefault(LocalStorageState.ONLINE_ONLY),
        fileSizeBytes = fileSizeBytes,
        mimeType = mimeType,
        offlineAvailable = offlineAvailable,
        playCount = playCount,
        lastPlayedAt = lastPlayedAt,
        cachedAt = cachedAt,
        dateAdded = dateAdded
    )

    companion object {
        fun fromDomain(track: Track): TrackEntity = TrackEntity(
            id = track.id,
            title = track.title,
            artist = track.artist,
            artistId = track.artistId,
            album = track.album,
            albumId = track.albumId,
            durationSeconds = track.durationSeconds,
            artworkUrl = track.artworkUrl,
            streamUrl = track.streamUrl,
            isLiked = track.isLiked,
            isDownloaded = track.isDownloaded,
            isCached = track.isCached,
            localFilePath = track.localFilePath,
            storageState = track.storageState.name,
            fileSizeBytes = track.fileSizeBytes,
            mimeType = track.mimeType,
            offlineAvailable = track.offlineAvailable,
            playCount = track.playCount,
            lastPlayedAt = track.lastPlayedAt,
            cachedAt = track.cachedAt,
            dateAdded = track.dateAdded
        )
    }
}

